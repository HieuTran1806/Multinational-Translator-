-- =====================================================================
-- V5: UC09/UC13/UC14/UC15 — seller accounts, audit log, usage analytics.
-- - account: soft delete (deleted_at/deleted_by) + SELLER role.
-- - access_qr: optional owning seller (seller issues QR to its customer;
--   in the MVP the Admin creates it on the seller's behalf).
-- - audit_log: append-only record of sensitive admin/business events.
-- - usage_event: raw usage metrics (poi_view, audio_play, session_start).
--   Raw events are purged after 90 days by a scheduled job; aggregates
--   are computed on the fly (dataset is small at MVP scale).
-- =====================================================================

-- ---------- account: SELLER role + soft delete ----------
ALTER TABLE account ADD COLUMN deleted_at TIMESTAMPTZ;
ALTER TABLE account ADD COLUMN deleted_by BIGINT REFERENCES account (id) ON DELETE SET NULL;

-- Uniqueness of username now applies only to live accounts; a soft-deleted
-- account's username can be reused by a new account.
ALTER TABLE account DROP CONSTRAINT uq_account_username;
CREATE UNIQUE INDEX uq_account_username_active ON account (username) WHERE deleted_at IS NULL;

ALTER TABLE account DROP CONSTRAINT ck_account_role;
ALTER TABLE account ADD CONSTRAINT ck_account_role CHECK (role IN ('ADMIN', 'SUPER_ADMIN', 'SELLER'));

-- ---------- access_qr: owning seller ----------
ALTER TABLE access_qr ADD COLUMN seller_id BIGINT REFERENCES account (id) ON DELETE SET NULL;
CREATE INDEX ix_access_qr_seller ON access_qr (seller_id, created_at DESC);

-- ---------- audit_log (UC15): append-only, no sensitive payloads ----------
CREATE TABLE audit_log (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    actor_id      BIGINT,                        -- account id, NULL for system events
    actor_name    VARCHAR(64),                   -- snapshot; survives account soft delete
    action        VARCHAR(40)  NOT NULL,         -- e.g. SELLER_CREATE, QR_REVOKE
    resource_type VARCHAR(40)  NOT NULL,         -- e.g. ACCOUNT, ACCESS_QR, AUTH_SESSION
    resource_id   VARCHAR(64),                   -- string form of the resource key
    result        VARCHAR(10)  NOT NULL,         -- SUCCESS / DENIED / FAILURE
    detail        TEXT,                          -- safe metadata only (never secrets/tokens)
    CONSTRAINT ck_audit_result CHECK (result IN ('SUCCESS', 'DENIED', 'FAILURE'))
);
CREATE INDEX ix_audit_log_time ON audit_log (occurred_at DESC);
CREATE INDEX ix_audit_log_action_time ON audit_log (action, occurred_at DESC);
CREATE INDEX ix_audit_log_actor_time ON audit_log (actor_id, occurred_at DESC);

-- ---------- usage_event (UC13/UC14 metrics) ----------
CREATE TABLE usage_event (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type  VARCHAR(20) NOT NULL,
    grant_id    BIGINT      NOT NULL REFERENCES access_grant (id) ON DELETE CASCADE,
    poi_id      BIGINT      REFERENCES poi (id) ON DELETE SET NULL,
    event_id    VARCHAR(64),                   -- client dedup key (uuid), unique when present
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_usage_event_type CHECK (event_type IN ('poi_view', 'audio_play', 'session_start'))
);
CREATE UNIQUE INDEX uq_usage_event_event_id ON usage_event (event_id) WHERE event_id IS NOT NULL;
CREATE INDEX ix_usage_event_type_time ON usage_event (event_type, occurred_at DESC);
CREATE INDEX ix_usage_event_poi ON usage_event (poi_id, occurred_at DESC);
