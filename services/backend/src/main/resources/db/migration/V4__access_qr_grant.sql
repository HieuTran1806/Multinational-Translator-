-- =====================================================================
-- V4: UC02 — single-use access QR codes and time-limited User grants.
-- No Tourist/User account exists: a redeemed QR becomes a grant bound to
-- the activating device. Tokens are stored as SHA-256 hashes only.
-- =====================================================================

-- ---------- Access packages (duration is data, not code) ----------
CREATE TABLE access_package (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                VARCHAR(40)  NOT NULL,
    name                VARCHAR(120) NOT NULL,
    duration_minutes    INT          NOT NULL,
    active              BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_access_package_code UNIQUE (code),
    CONSTRAINT ck_access_package_duration CHECK (duration_minutes > 0)
);

-- Demo package from the BRD: 24 hours counted from a successful redeem.
INSERT INTO access_package (code, name, duration_minutes) VALUES ('DEMO_24H', 'Gói demo 24 giờ', 1440);

-- ---------- Access QR codes (single use, no expiry before redeem, revocable) ----------
CREATE TABLE access_qr (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash      VARCHAR(64)  NOT NULL,           -- SHA-256 hex of the QR token
    package_id      BIGINT       NOT NULL REFERENCES access_package (id),
    status          VARCHAR(10)  NOT NULL DEFAULT 'ISSUED',
    note            VARCHAR(200),
    issued_by       BIGINT       REFERENCES account (id) ON DELETE SET NULL,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    redeemed_at     TIMESTAMPTZ,
    revoked_at      TIMESTAMPTZ,
    CONSTRAINT uq_access_qr_token UNIQUE (token_hash),
    CONSTRAINT ck_access_qr_status CHECK (status IN ('ISSUED', 'REDEEMED', 'REVOKED'))
);
CREATE INDEX ix_access_qr_status_created ON access_qr (status, created_at DESC);

-- ---------- Grants (one per redeemed QR, bound to one device) ----------
CREATE TABLE access_grant (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    qr_id           BIGINT       NOT NULL REFERENCES access_qr (id) ON DELETE CASCADE,
    token_hash      VARCHAR(64)  NOT NULL,           -- SHA-256 hex of the grant bearer token
    device_hash     VARCHAR(64)  NOT NULL,           -- SHA-256 hex of the client device id
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    expires_at      TIMESTAMPTZ  NOT NULL,
    revoked_at      TIMESTAMPTZ,
    -- Backstop for the atomic redeem: a QR can never produce two grants.
    CONSTRAINT uq_access_grant_qr UNIQUE (qr_id),
    CONSTRAINT uq_access_grant_token UNIQUE (token_hash)
);
CREATE INDEX ix_access_grant_expires ON access_grant (expires_at);
