-- Align POI admin data with UC10 while preserving existing rows and media.
ALTER TABLE poi ADD COLUMN category VARCHAR(100);
ALTER TABLE poi ADD COLUMN trigger_radius DOUBLE PRECISION NOT NULL DEFAULT 50.0;
ALTER TABLE poi ADD COLUMN deleted_at TIMESTAMPTZ;
ALTER TABLE poi ADD CONSTRAINT ck_poi_trigger_radius CHECK (trigger_radius BETWEEN 1 AND 5000);
CREATE INDEX ix_poi_deleted_at ON poi (deleted_at);

-- Multi-image metadata. Existing cover images are retained and copied as the first image.
CREATE TABLE poi_image (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    poi_id BIGINT NOT NULL REFERENCES poi(id) ON DELETE CASCADE,
    storage_key VARCHAR(255) NOT NULL UNIQUE,
    mime_type VARCHAR(50) NOT NULL,
    sort_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_poi_image_sort_order CHECK (sort_order >= 0)
);
CREATE INDEX ix_poi_image_order ON poi_image (poi_id, sort_order, id);
INSERT INTO poi_image (poi_id, storage_key, mime_type, sort_order)
SELECT id, cover_image_key, COALESCE(cover_image_type, 'application/octet-stream'), 0
FROM poi WHERE cover_image_key IS NOT NULL;
