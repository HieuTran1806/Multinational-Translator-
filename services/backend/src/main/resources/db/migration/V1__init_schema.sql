-- =====================================================================
-- V1: initial schema for "Thuyết minh đa ngôn ngữ" MVP
-- Schema is managed ONLY by Flyway (spring.jpa.hibernate.ddl-auto=validate)
-- =====================================================================

-- ---------- Accounts (administrators) ----------
CREATE TABLE account (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR(64)  NOT NULL,
    password_hash   VARCHAR(100) NOT NULL,           -- BCrypt hash, never plaintext
    display_name    VARCHAR(120),
    role            VARCHAR(20)  NOT NULL,
    enabled         BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_account_username UNIQUE (username),
    CONSTRAINT ck_account_role CHECK (role IN ('ADMIN', 'SUPER_ADMIN')),
    CONSTRAINT ck_account_username_format CHECK (username ~ '^[a-zA-Z0-9_.-]{3,64}$')
);

-- ---------- Login sessions (opaque bearer tokens, stored hashed) ----------
CREATE TABLE auth_session (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id      BIGINT       NOT NULL REFERENCES account (id) ON DELETE CASCADE,
    token_hash      VARCHAR(64)   NOT NULL,           -- SHA-256 hex of the token
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    expires_at      TIMESTAMPTZ  NOT NULL,
    last_used_at    TIMESTAMPTZ,
    revoked_at      TIMESTAMPTZ,
    CONSTRAINT uq_auth_session_token UNIQUE (token_hash)
);
CREATE INDEX ix_auth_session_account ON auth_session (account_id);
CREATE INDEX ix_auth_session_expires ON auth_session (expires_at);

-- ---------- Languages ----------
CREATE TABLE language (
    code                VARCHAR(10)  PRIMARY KEY,     -- BCP-47 short code: vi, en
    name                VARCHAR(60)  NOT NULL,        -- English name
    native_name         VARCHAR(60)  NOT NULL,
    tts_language_code   VARCHAR(20)  NOT NULL,        -- e.g. vi-VN, en-US
    default_tts_voice   VARCHAR(80),                  -- e.g. vi-VN-Standard-A (nullable = provider default)
    enabled             BOOLEAN      NOT NULL DEFAULT TRUE,
    sort_order          INT          NOT NULL DEFAULT 0,
    CONSTRAINT ck_language_code_format CHECK (code ~ '^[a-z]{2,3}(-[A-Za-z0-9]{2,8})?$')
);

-- ---------- Points of interest ----------
CREATE TABLE poi (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                VARCHAR(50)       NOT NULL,
    default_name        VARCHAR(200)      NOT NULL,
    latitude            DOUBLE PRECISION  NOT NULL,
    longitude           DOUBLE PRECISION  NOT NULL,
    cover_image_key     VARCHAR(255),                 -- storage key, NOT an absolute URL
    cover_image_type    VARCHAR(50),
    status              VARCHAR(20)       NOT NULL DEFAULT 'DRAFT',
    is_demo             BOOLEAN           NOT NULL DEFAULT FALSE,
    published_at        TIMESTAMPTZ,
    created_at          TIMESTAMPTZ       NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ       NOT NULL DEFAULT now(),
    row_version         BIGINT            NOT NULL DEFAULT 0,   -- optimistic locking
    CONSTRAINT uq_poi_code UNIQUE (code),
    CONSTRAINT ck_poi_code_format CHECK (code ~ '^[A-Z0-9][A-Z0-9_-]{1,49}$'),
    CONSTRAINT ck_poi_status CHECK (status IN ('DRAFT', 'PUBLISHED')),
    CONSTRAINT ck_poi_latitude CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_poi_longitude CHECK (longitude BETWEEN -180 AND 180)
);
CREATE INDEX ix_poi_status ON poi (status);
CREATE INDEX ix_poi_updated_at ON poi (updated_at DESC);

-- ---------- Per-language content ----------
CREATE TABLE poi_translation (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    poi_id              BIGINT        NOT NULL REFERENCES poi (id) ON DELETE CASCADE,
    language_code       VARCHAR(10)   NOT NULL REFERENCES language (code),
    name                VARCHAR(200)  NOT NULL,
    description         TEXT,
    narration_text      TEXT          NOT NULL,
    -- incremented whenever narration_text changes; audio is bound to a version
    content_version     INT           NOT NULL DEFAULT 1,
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_poi_translation_poi_lang UNIQUE (poi_id, language_code),
    CONSTRAINT ck_poi_translation_version CHECK (content_version >= 1),
    CONSTRAINT ck_poi_translation_narration CHECK (length(btrim(narration_text)) > 0)
);
CREATE INDEX ix_poi_translation_lang ON poi_translation (language_code);

-- ---------- Audio files (metadata only; bytes live in MediaStorage) ----------
CREATE TABLE audio_asset (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    translation_id      BIGINT        NOT NULL REFERENCES poi_translation (id) ON DELETE CASCADE,
    content_version     INT           NOT NULL,       -- translation.content_version this audio was made for
    storage_key         VARCHAR(255)  NOT NULL,
    source              VARCHAR(10)   NOT NULL,
    format              VARCHAR(10)   NOT NULL,       -- mp3 | m4a | wav | ogg
    mime_type           VARCHAR(50)   NOT NULL,
    size_bytes          BIGINT        NOT NULL,
    sha256              VARCHAR(64)    NOT NULL,
    status              VARCHAR(10)   NOT NULL,
    content_hash        VARCHAR(64),                     -- TTS only: hash(text, language, voice, encoding)
    tts_voice           VARCHAR(80),
    original_filename   VARCHAR(255),
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_audio_asset_storage_key UNIQUE (storage_key),
    CONSTRAINT ck_audio_asset_source CHECK (source IN ('UPLOAD', 'TTS')),
    CONSTRAINT ck_audio_asset_format CHECK (format IN ('mp3', 'm4a', 'wav', 'ogg')),
    CONSTRAINT ck_audio_asset_status CHECK (status IN ('READY', 'STALE')),
    CONSTRAINT ck_audio_asset_size CHECK (size_bytes > 0),
    CONSTRAINT ck_audio_asset_tts_hash CHECK (source <> 'TTS' OR content_hash IS NOT NULL)
);
CREATE INDEX ix_audio_asset_translation ON audio_asset (translation_id, status, content_version);
CREATE INDEX ix_audio_asset_content_hash ON audio_asset (content_hash) WHERE content_hash IS NOT NULL;

-- ---------- Asynchronous TTS jobs (durable, polled by a worker) ----------
CREATE TABLE audio_generation_job (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    translation_id      BIGINT        NOT NULL REFERENCES poi_translation (id) ON DELETE CASCADE,
    content_version     INT           NOT NULL,
    content_hash        VARCHAR(64)    NOT NULL,
    language_code       VARCHAR(10)   NOT NULL REFERENCES language (code),
    tts_voice           VARCHAR(80),
    status              VARCHAR(12)   NOT NULL DEFAULT 'QUEUED',
    attempts            INT           NOT NULL DEFAULT 0,
    max_attempts        INT           NOT NULL DEFAULT 3,
    next_attempt_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    error_code          VARCHAR(50),
    error_message       VARCHAR(500),
    audio_asset_id      BIGINT        REFERENCES audio_asset (id) ON DELETE SET NULL,
    requested_by        BIGINT        REFERENCES account (id) ON DELETE SET NULL,
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    started_at          TIMESTAMPTZ,
    finished_at         TIMESTAMPTZ,
    updated_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_job_status CHECK (status IN ('QUEUED', 'RUNNING', 'SUCCEEDED', 'FAILED')),
    CONSTRAINT ck_job_attempts CHECK (attempts >= 0 AND max_attempts >= 1)
);
CREATE INDEX ix_job_pick ON audio_generation_job (status, next_attempt_at);
CREATE INDEX ix_job_translation ON audio_generation_job (translation_id, created_at DESC);
-- at most one active job for the same content
CREATE UNIQUE INDEX uq_job_active_content
    ON audio_generation_job (translation_id, content_hash)
    WHERE status IN ('QUEUED', 'RUNNING');
