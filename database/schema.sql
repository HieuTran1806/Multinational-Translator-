-- Multitional Translator — consolidated PostgreSQL schema
-- Source: Neon production (branch: production), verified against Flyway V1–V6.
-- Snapshot only: no application data, secrets, or Flyway schema history.
-- PostgreSQL 18; compatible with PostgreSQL 15+.
-- Restore into an empty database. Then baseline Flyway at version 6 (see README.md).

BEGIN;
SET search_path TO public;

CREATE TABLE account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    display_name VARCHAR(120),
    role VARCHAR(20) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ,
    deleted_by BIGINT REFERENCES account(id) ON DELETE SET NULL,
    CONSTRAINT ck_account_role CHECK (role IN ('ADMIN', 'SUPER_ADMIN')),
    CONSTRAINT ck_account_username_format CHECK (username ~ '^[a-zA-Z0-9_.-]{3,64}$')
);
CREATE UNIQUE INDEX uq_account_username_active ON account(username) WHERE deleted_at IS NULL;

CREATE TABLE auth_session (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account(id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,
    last_used_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    CONSTRAINT uq_auth_session_token UNIQUE(token_hash)
);
CREATE INDEX ix_auth_session_account ON auth_session(account_id);
CREATE INDEX ix_auth_session_expires ON auth_session(expires_at);

CREATE TABLE language (
    code VARCHAR(10) PRIMARY KEY,
    name VARCHAR(60) NOT NULL,
    native_name VARCHAR(60) NOT NULL,
    tts_language_code VARCHAR(20) NOT NULL,
    default_tts_voice VARCHAR(80),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order INT NOT NULL DEFAULT 0,
    CONSTRAINT ck_language_code_format CHECK (code ~ '^[a-z]{2,3}(-[A-Za-z0-9]{2,8})?$')
);

CREATE TABLE poi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL,
    default_name VARCHAR(200) NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    cover_image_key VARCHAR(255),
    cover_image_type VARCHAR(50),
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    is_demo BOOLEAN NOT NULL DEFAULT FALSE,
    published_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    row_version BIGINT NOT NULL DEFAULT 0,
    category VARCHAR(100),
    trigger_radius DOUBLE PRECISION NOT NULL DEFAULT 50.0,
    deleted_at TIMESTAMPTZ,
    CONSTRAINT uq_poi_code UNIQUE(code),
    CONSTRAINT ck_poi_code_format CHECK (code ~ '^[A-Z0-9][A-Z0-9_-]{1,49}$'),
    CONSTRAINT ck_poi_status CHECK (status IN ('DRAFT', 'PUBLISHED')),
    CONSTRAINT ck_poi_latitude CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_poi_longitude CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_poi_trigger_radius CHECK (trigger_radius BETWEEN 1 AND 5000)
);
CREATE INDEX ix_poi_status ON poi(status);
CREATE INDEX ix_poi_updated_at ON poi(updated_at DESC);
CREATE INDEX ix_poi_deleted_at ON poi(deleted_at);

CREATE TABLE poi_translation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    poi_id BIGINT NOT NULL REFERENCES poi(id) ON DELETE CASCADE,
    language_code VARCHAR(10) NOT NULL REFERENCES language(code),
    name VARCHAR(200) NOT NULL,
    description TEXT,
    narration_text TEXT NOT NULL,
    content_version INT NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_poi_translation_poi_lang UNIQUE(poi_id, language_code),
    CONSTRAINT ck_poi_translation_version CHECK (content_version >= 1),
    CONSTRAINT ck_poi_translation_narration CHECK (length(btrim(narration_text)) > 0)
);
CREATE INDEX ix_poi_translation_lang ON poi_translation(language_code);

CREATE TABLE audio_asset (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    translation_id BIGINT NOT NULL REFERENCES poi_translation(id) ON DELETE CASCADE,
    content_version INT NOT NULL,
    storage_key VARCHAR(255) NOT NULL,
    source VARCHAR(10) NOT NULL,
    format VARCHAR(10) NOT NULL,
    mime_type VARCHAR(50) NOT NULL,
    size_bytes BIGINT NOT NULL,
    sha256 VARCHAR(64) NOT NULL,
    status VARCHAR(10) NOT NULL,
    content_hash VARCHAR(64),
    tts_voice VARCHAR(80),
    original_filename VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_audio_asset_storage_key UNIQUE(storage_key),
    CONSTRAINT ck_audio_asset_source CHECK (source IN ('UPLOAD', 'TTS')),
    CONSTRAINT ck_audio_asset_format CHECK (format IN ('mp3', 'm4a', 'wav', 'ogg')),
    CONSTRAINT ck_audio_asset_status CHECK (status IN ('READY', 'STALE')),
    CONSTRAINT ck_audio_asset_size CHECK (size_bytes > 0),
    CONSTRAINT ck_audio_asset_tts_hash CHECK (source <> 'TTS' OR content_hash IS NOT NULL)
);
CREATE INDEX ix_audio_asset_translation ON audio_asset(translation_id, status, content_version);
CREATE INDEX ix_audio_asset_content_hash ON audio_asset(content_hash) WHERE content_hash IS NOT NULL;

CREATE TABLE audio_generation_job (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    translation_id BIGINT NOT NULL REFERENCES poi_translation(id) ON DELETE CASCADE,
    content_version INT NOT NULL,
    content_hash VARCHAR(64) NOT NULL,
    language_code VARCHAR(10) NOT NULL REFERENCES language(code),
    tts_voice VARCHAR(80),
    status VARCHAR(12) NOT NULL DEFAULT 'QUEUED',
    attempts INT NOT NULL DEFAULT 0,
    max_attempts INT NOT NULL DEFAULT 3,
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    error_code VARCHAR(50),
    error_message VARCHAR(500),
    audio_asset_id BIGINT REFERENCES audio_asset(id) ON DELETE SET NULL,
    requested_by BIGINT REFERENCES account(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_job_status CHECK (status IN ('QUEUED', 'RUNNING', 'SUCCEEDED', 'FAILED')),
    CONSTRAINT ck_job_attempts CHECK (attempts >= 0 AND max_attempts >= 1)
);
CREATE INDEX ix_job_pick ON audio_generation_job(status, next_attempt_at);
CREATE INDEX ix_job_translation ON audio_generation_job(translation_id, created_at DESC);
CREATE UNIQUE INDEX uq_job_active_content
    ON audio_generation_job(translation_id, content_hash)
    WHERE status IN ('QUEUED', 'RUNNING');

CREATE TABLE poi_image (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    poi_id BIGINT NOT NULL REFERENCES poi(id) ON DELETE CASCADE,
    storage_key VARCHAR(255) NOT NULL UNIQUE,
    mime_type VARCHAR(50) NOT NULL,
    sort_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_poi_image_sort_order CHECK (sort_order >= 0)
);
CREATE INDEX ix_poi_image_order ON poi_image(poi_id, sort_order, id);

CREATE TABLE access_package (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL,
    name VARCHAR(120) NOT NULL,
    duration_minutes INT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_access_package_code UNIQUE(code),
    CONSTRAINT ck_access_package_duration CHECK (duration_minutes > 0)
);

CREATE TABLE access_qr (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash VARCHAR(64) NOT NULL,
    package_id BIGINT NOT NULL REFERENCES access_package(id),
    status VARCHAR(10) NOT NULL DEFAULT 'ISSUED',
    note VARCHAR(200),
    issued_by BIGINT REFERENCES account(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    redeemed_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    CONSTRAINT uq_access_qr_token UNIQUE(token_hash),
    CONSTRAINT ck_access_qr_status CHECK (status IN ('ISSUED', 'REDEEMED', 'REVOKED'))
);
CREATE INDEX ix_access_qr_status_created ON access_qr(status, created_at DESC);

CREATE TABLE access_grant (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    qr_id BIGINT NOT NULL REFERENCES access_qr(id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL,
    device_hash VARCHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    CONSTRAINT uq_access_grant_qr UNIQUE(qr_id),
    CONSTRAINT uq_access_grant_token UNIQUE(token_hash)
);
CREATE INDEX ix_access_grant_expires ON access_grant(expires_at);

CREATE TABLE audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    actor_id BIGINT,
    actor_name VARCHAR(64),
    action VARCHAR(40) NOT NULL,
    resource_type VARCHAR(40) NOT NULL,
    resource_id VARCHAR(64),
    result VARCHAR(10) NOT NULL,
    detail TEXT,
    CONSTRAINT ck_audit_result CHECK (result IN ('SUCCESS', 'DENIED', 'FAILURE'))
);
CREATE INDEX ix_audit_log_time ON audit_log(occurred_at DESC);
CREATE INDEX ix_audit_log_action_time ON audit_log(action, occurred_at DESC);
CREATE INDEX ix_audit_log_actor_time ON audit_log(actor_id, occurred_at DESC);

CREATE TABLE usage_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type VARCHAR(20) NOT NULL,
    grant_id BIGINT NOT NULL REFERENCES access_grant(id) ON DELETE CASCADE,
    poi_id BIGINT REFERENCES poi(id) ON DELETE SET NULL,
    event_id VARCHAR(64),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_usage_event_type CHECK (event_type IN ('poi_view', 'audio_play', 'session_start'))
);
CREATE UNIQUE INDEX uq_usage_event_event_id ON usage_event(event_id) WHERE event_id IS NOT NULL;
CREATE INDEX ix_usage_event_type_time ON usage_event(event_type, occurred_at DESC);
CREATE INDEX ix_usage_event_poi ON usage_event(poi_id, occurred_at DESC);

COMMIT;
