export const UI_FALLBACKS = ['en', 'vi'];

/** UI locale for a content language: its own dictionary when present, else English, else Vietnamese. */
export function uiLocale(lang) {
  if (MESSAGES[lang]) return lang;
  return UI_FALLBACKS.find((l) => MESSAGES[l]);
}

/** Translate `key` for `lang`, replacing `{name}` placeholders. Unknown keys fall back, then show the key. */
export function translate(lang, key, params) {
  const locale = uiLocale(lang);
  const text = MESSAGES[locale]?.[key] ?? MESSAGES.vi[key] ?? key;
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (m, name) => (params[name] ?? m));
}

/** BCP-47 tag for dates/times in the UI locale. */
export function intlLocale(lang) {
  return uiLocale(lang) === 'vi' ? 'vi-VN' : 'en-GB';
}
